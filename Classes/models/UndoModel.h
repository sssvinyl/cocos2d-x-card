#ifndef __UNDO_MODEL_H__
#define __UNDO_MODEL_H__

#include "cocos2d.h"

class CardModel;

 /**
  * @class UndoModel
  * @brief ???????????????????????????
  *
  * ?????????????
  *   - HAND_SWAP: ????????????????????????????????????
  *   - MATCH_MOVE: ??????????????????????????
  */
class UndoModel : public cocos2d::Ref
{
public:

    enum class OpType
    {
        HAND_SWAP = 0,
        MATCH_MOVE = 1,
        STOCK_DRAW = 2
    };


    OpType opType;


    int movedCardId;


    int fromPileType;


    int fromIndex;


    cocos2d::Vec2 fromPosition;

 
    int toPileType;


    int toIndex;

    cocos2d::Vec2 toPosition;

    /**
     * ?????????????????????????????????????????ID
     * ???? opType == HAND_SWAP ?????
     */
    int displacedCardId;

    /**
     * ???????????????????????????????????
     * ???? opType == HAND_SWAP ?????
     */
    int displacedCardNewIndex;

    CardModel* displacedCardModel;

public:
    UndoModel()
        : opType(OpType::HAND_SWAP)
        , movedCardId(-1)
        , fromPileType(0)
        , fromIndex(-1)
        , fromPosition(cocos2d::Vec2::ZERO)
        , toPileType(0)
        , toIndex(-1)
        , toPosition(cocos2d::Vec2::ZERO)
        , displacedCardId(-1)
        , displacedCardNewIndex(-1)
        , displacedCardModel(nullptr)
    {
    }

    static UndoModel* create()
    {
        UndoModel* model = new (std::nothrow) UndoModel();
        if (model)
        {
            model->autorelease();
        }
        return model;
    }
};

#endif // __UNDO_MODEL_H__